/* 验收标准前置条件："实验报告记录，各参数需要至少采样1000个真实AD数据"。
 * 波形帧（0x33/0x02）本身就是原始 AD，用上位机录 2 秒就有 1000 点；本导出功能
 * 是给"没有上位机、只有串口助手"的场合兜底。
 *
 * 【为什么是"从最新点往回倒着读"】屏缓冲是 2048 点的环形缓冲，采样仍以 500SPS
 * 在往里写。若从最老的点顺着读，读到一半就会被新数据覆盖（画面撕裂）。
 * 倒着读（先发最新点、再发更早的点）时，发送速度 8点/10ms = 800点/s 快于
 * 采样速度 500点/s，所以我们读的位置只会越来越"旧"，永远不会被写指针追上：
 *   读完 1024 点需要 128 行 × 10ms = 1.28s，此间写指针前进 640 点，
 *   而最老的读取点只回溯到 1024 —— 1024 + 640 = 1664 < 2048，安全余量充足。
 * 这样导出的 1024 点是一次**无撕裂的一致快照**，可直接写进实验报告。*/
#define SPO2_DUMP_POINTS        1024u  /* 每次导出多少对(IR,RED)；1024 ≥ 1000，满足验收 */
#define SPO2_DUMP_PER_LINE      8u     /* 每行打印 8 对，行数 = 1024/8 = 128 */
#define SPO2_DUMP_TICK_DIV      5u     /* 每 5 个 2ms 节拍(10ms)发一行 → 约 1.28s 发完 */

/* 【编译期硬约束】"每行读走的点数"必须 ≥ "每行期间新写入的点数"，也就是
 * (SPO2_DUMP_PER_LINE) ≥ (SPO2_DUMP_TICK_DIV)。两者相等就已经不安全
 * （读指针会被写指针匀速追上），必须留裕量。这正是一致快照成立的前提。*/
#if (SPO2_DUMP_PER_LINE <= SPO2_DUMP_TICK_DIV)
#error "SPO2_DUMP_PER_LINE must be GREATER than SPO2_DUMP_TICK_DIV (see spo2_config.h AD dump note)"
#endif

