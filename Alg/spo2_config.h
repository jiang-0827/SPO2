/*********************************************************************************************************
:*                                              采样与前端（M1/M3）
*********************************************************************************************************/
/* 前端为"IR/RED 分时选通 + 单路 VSIG"结构：一个采样节拍(2ms)内先选通 IR 采一点，
 * 再选通 RED 采一点，因此 IR/RED 各自 500 SPS，与 MATLAB 侧的 Fs=500 严格对齐。*/
#define SPO2_FS                 500.0f     /* 每通道采样率 SPS，由 TIM4 的 2ms 时间片驱动 */
#define SPO2_T                  (1.0f / SPO2_FS)  /* 2 ms/样本 → 168MHz 下 336000 cycle 预算 */

#define SPO2_ADC_BITS           12
#define SPO2_ADC_FULL           4095u      /* 2^12 - 1 */
#define SPO2_ADC_VREF           3.3f       /* [实测] VREF+ 必须与 VDDA 同源 */
#define SPO2_ADC_BIAS_CODE      2048u      /* 前端静态工作点码值（VREF/2），滤波前先扣除 */
#define SPO2_ADC_UV_PER_LSB     (SPO2_ADC_VREF / (float)SPO2_ADC_FULL * 1e6f)  /* ≈806 μV/LSB */

/* 前端通道选通后的建立时间（μs）。模拟开关 SGM3005 的 tON/tOFF 为百 ns 级，
 * 真正决定建立时间的是跨阻级的 RC（原理图 C10/C11 与 R12/R13）。[实测]
 * 太小 → 通道间串扰（IR 采样点里混进 RED 的充电尾巴）；太大 → 挤占 2ms 预算。*/
#define SPO2_FE_SETTLE_US       100u

/* 前端输出极性：0 = 归一后码值直接用原始 ADC（要求"原始码值越小 = 光越强"）
 *               1 = 归一后码值 = 4095 - 原始 ADC（把原始极性翻过来）
 *
 * 【本工程实测结论：必须为 0】
 *   ① 手指拿掉后，串口看到的 IR 归一码值从 ~750 跳到 ~4000（见 wave.csv）；
 *      换算成原始 ADC：750 → raw 3345 ；4000 → raw 95。
 *      即"光越强（LED 直射光电管）→ raw 越小"，所以原始极性本来就是
 *      "码值小 = 光强"，**不需要再翻一次**。
 *   ② 若错设为 1（多加一次 4095-raw），会同时搞坏三件事：
 *      - 光强闭环变成正反馈：IR 归一 285 被当成"光已够足"而停调（实际很暗），
 *        RED 归一 3997 被当成"光不够"而把 DA 一路顶到 250（实际过曝）；
 *      - 脉搏波方向翻转，画出来是朝下的尖峰；
 *      - 两个脱落判据互相对调：无手指（raw≈95）被当成"无光"，无光（raw≈4000）
 *        被当成"光过强"，报出来的脱落类型正好相反。
 *   ③ 在线试：CMD_SPO2_SET_INVERT(0x86) 可运行时切换，改完立即看波形与
 *      irAd；确认后把本宏固化（复位后仍以此宏为准）。
 *   约定来源：MATLAB 侧 IR_CENTRAL_LINE=2000、"AD 值小于 80 判脱落"都建立在
 *   "码值小 = 光强"之上，归一化就是为了把前端统一到这个约定。*/
#define SPO2_FE_INVERT          0u

/* ADC 过采样次数：每个通道连续转换 N 次取平均（不改变 500SPS 的采样率，只降噪声）。
 * 【验收对应】验收要求"滤除随机噪声"，且模拟器灌注指数固定 3%（交流峰峰值只有
 * DC 的 3% 左右，若 DC 调到 2000，交流峰峰值 ≈ 60 码），此时单个 LSB 的量化台阶
 * 就带来 ~1.7% 的相对误差，直接吃掉血氧 ±2% 的精度预算。过采样+平均把白噪声降
 * sqrt(N) 倍：N=1 不降；N=4 降 2 倍(+6dB，等效多约 1bit)；N=8 降 2.8 倍。
 * 代价：单次转换约 23μs，N=4 时每 2ms 节拍多用 2*4*23 ≈ 184μs（约 9% CPU）。
 * [实测] 若通道建立时间已吃掉太多 2ms 预算，可降到 2 或 1。*/
#define SPO2_ADC_OS             4u

/*********************************************************************************************************
:*                    前端基线复位开关 SPO2_CAP（2026-10-08 版血氧板 H4-5 → Q1 AO3401A 栅极）
:* 硬件事实：C8 是串联交流耦合，改光强/插拔手指会让 C8 之后的直流跳一个台阶（把脉搏波顶偏，
:*           严重时顶出 ADC 量程）；板上预留 Q1，导通时把该节点经 R23 270Ω 钳回 VREF，
:*           即为"基线复位"，R23×C8 = 27μs，5τ≈135μs；栅极网络只有 2 个端点、**没有板上拉**，
:*           必须由 MCU 显式驱动（低电平=复位，高电平=正常测量），不能悬空。
:* 决策：实测判定不启用（基线台阶靠 AGC 慢速收敛吸收，不影响出数据与出波形），
:*       驱动代码已于 2026-10-10 整条移除。若要重启：重配 PC6 推挽输出，并在采样节拍
:*       （ReadPair 里光强已写进 DAC 之后）插一个 200μs 脉冲，不要放在中断上下文里。
*********************************************************************************************************/

