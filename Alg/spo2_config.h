#define SPO2_FILT_NOTCH_BETA    0.96f  /* 极点半径 → 3dB 缺口宽 ≈ 3.3*(1-beta)*Fs/pi ≈ 21.0 Hz */
#define SPO2_FILT_FPASS         20.0f  /* Hz 通带上限（= MATLAB gFiltFc 默认值） */
#define SPO2_FILT_ORDER         5u     /* 低通阶数（= MATLAB gFiltDegree 默认值） */

/*********************************************************************************************************
:*                                              脉率（对应 CalcPulseRate.m）
*********************************************************************************************************/
/* 【验收对应】"脉率范围 30~200BPM，误差 ±5%"
 *   MATLAB 原值是 20~120bpm，达不到验收下限/上限，这里按验收标准放宽：
 *     下限 20 → 30 : 验收下限；同时挡掉呼吸/体动引起的 20~30bpm 慢波
 *     上限 120 → 200: 验收上限
 *   上限放宽后**必须同步改 SPO2_PR_MIN_DIST**：原 250 样本(0.5s)等价于
 *   "最大可测 120bpm"，而 200bpm 的 RR = 60*500/200 = 150 样本，不应期必须
 *   小于 150，否则每两次心跳就被吃掉一次，读数直接减半（这是最容易踩的坑）。*/
#define SPO2_PR_MIN             30     /* bpm 合法下限 [验收: 30~200] */
#define SPO2_PR_MAX             200    /* bpm 合法上限 [验收: 30~200] */
/* 不应期 = findpeaks 的 MinPeakDistance。取 135 样本 = 0.27s：
 *   上限 → 60*500/135 = 222bpm，对 200bpm 留 11% 裕量；
 *   下限 → 135 > 0.2s，仍能压住大部分重搏波（dicrotic notch）。*/
#define SPO2_PR_MIN_DIST        135u   /* 0.27s @500SPS（原 250 = 0.5s 只够 120bpm）*/
#define SPO2_PR_BUF_LEN         6u     /* gPRBuf 深度：6 点中值（取排序后中间两个求平均） */
#define SPO2_PR_SEED            75     /* gPRBuf / ResetAdj 的复位值（保住 MATLAB 的数值行为） */
#define SPO2_PR_MAX_RR          8u     /* 参与 median(RR) 的最近 RR 个数 */
#define SPO2_PR_MIN_RR_OUT      2u     /* 至少累计多少个 RR 才输出脉率 */
/* [实测] 原 MATLAB 用 findpeaks('minpeakheight',100)，那是"模块 24bit 原始码值"域
 * 的绝对门限。C 侧把峰值检测搬到了滤波后的交流域（见 spo2_pulse.h 的说明），
 * 量纲完全不同，故此处改为"自适应门限的偏置量"，必须按实采波形重新标定。*/
#define SPO2_PR_ABS_MIN         3      /* 窗内峰峰值小于此值 → 判信号丢失，不输出脉率 [实测] */
#define SPO2_PR_WIN_LEN         2048u  /* 自适应门限统计窗 = 4.096s */
#define SPO2_PR_BLK_LEN         64u    /* 滑动窗最大值分块长度：2048/64 = 32 块 */
#define SPO2_PR_CONFIRM_FALL    3u     /* 连续 N 样本不创新高 → 确认峰（代价：N*2ms 判决延迟） */
#define SPO2_PR_THR_ALPHA       0.6f   /* 门限 = min + alpha*(max-min) */

/*********************************************************************************************************
:*                                              血氧饱和度（对应 CalcSPO2.m）
*********************************************************************************************************/
#define SPO2_R_BUF_LEN          6u     /* gRValBuff 深度 */
#define SPO2_R_SEED             560    /* gRValBuff / ResetAdj 的复位值（R 值中值缓冲初值） */
#define SPO2_R_RATIO_SCALE      1000   /* R = redADRng * SPO2_R_RATIO_SCALE / irADRng */
#define SPO2_R_TABLE_LEN        11u    /* RR_TABLE 长度 */
#define SPO2_R_INDEX_BASE       101    /* spo2 = 101 - index；index 从 1 起算 */
#define SPO2_SAT_MAX            99     /* spo2 == 100 时按 99 上报（与 MATLAB 一致） */
/* 【验收对应】"血氧范围 90~99%，误差 ±2%"
 * 表覆盖范围：index 1..11 → SpO2 100..90（100 被钳到 99），即 90~99% 全覆盖，
 * 验收区间外不承诺精度。误差靠下面两件事保证：
 *   ① 交流幅度分辨率：PI=3% 时交流峰峰值只有 DC 的 3%，见 SPO2_ADC_OS 过采样；
 *   ② 曲线标定：spo2_coeffs.c 的 SPO2_RR_TABLE 是 MATLAB 原表，换成你的模拟器
 *      后必须用 CMD_SPO2_R_CAL 现场微调（见下面 R 值标定节），
 *      把模拟器的 90%/95%/99% 三档都压进 ±2%。*/

/* R 值算式的直流归一化开关：
 *   0 = MATLAB 原式  R = redADRng * 1000 / irADRng          （与 RR_TABLE 配套）
 *   1 = 标准定义式   R = (redADRng/redAvg) / (irADRng/irAvg) * 1000
 * 两者的比值恒为 redAvg/irAvg。光强调节把 IR 与 RED 的直流分别稳在各自的
 * 中线上（SPO2_IR_CENTRAL_LINE / SPO2_RED_CENTRAL_LINE），若这两条中线不等，
 * 原式就带一个固定的系统偏置。**默认必须保持 0**：RR_TABLE 是在原式下整定的，
 * 改成 1 会让表失配；只有在"重新整定过 RR_TABLE"之后才允许打开。*/
#define SPO2_R_DC_NORM          0u

/* R 值现场标定：R_used = R_raw * gain/1000 + offset（两者都是整数，无浮点）
 * 默认 gain=1000/offset=0 即"不标定"，行为与 MATLAB 完全一致。
 * 标定流程见 CMD_SPO2_R_CAL。这是把模拟器读数压进 ±2% 的唯一手段。*/
#define SPO2_R_CAL_GAIN_DEF     1000   /* 千分比增益（1000 = 不放大）*/
#define SPO2_R_CAL_OFFSET_DEF   0      /* R 值绝对偏置（0 = 不平移）*/
/* 允许范围要留够：两点标定解出的增益可能落到 0.5~2.5 倍之间
 * （取决于探头 R 值与 MATLAB 原表的差距），太窄会在现场"标不上"。*/
#define SPO2_R_CAL_GAIN_MIN     200
#define SPO2_R_CAL_GAIN_MAX     2500
#define SPO2_R_CAL_OFF_MIN      (-600)
#define SPO2_R_CAL_OFF_MAX      600

/*********************************************************************************************************
:*                                              灌注指数 PI（新增，对应验收项"灌注值数 3%"）
*********************************************************************************************************/
/* PI（Perfusion Index，灌注指数）= 交流分量 / 直流分量 × 100%
 *   PI_ir  = (irRng/2) / irAvg * 100 = irRng * 50 / irAvg   （%）
 * 这里统一放大 100 倍存成整数，即 "PI×100"，3.00% → 300，避免 %f（MicroILB 不支持）。
 * 【验收对应】验收标准写明"模拟器固定输出 3% 的灌注指数"，所以：
 *   ① 上位机读到 PI×100 ≈ 300 就是定量验证"灌注指数"这一项；
 *   ② PI 同时是最好的"手指是否真的贴在探头上"的判据（脱落时 PI ≈ 0），
 *      用 SPO2_PI_VALID_MIN_X100 参与脱落判决。*/
#define SPO2_PI_SCALE           100u   /* PI 整数放大倍数（PI×100 = 百分数的 100 倍）*/
#define SPO2_PI_MAX_X100        2000u  /* 20.00% 封顶（超过它说明根本不是脉搏波，防溢出）*/
#define SPO2_PI_VALID_MIN_X100  20u    /* PI < 0.20% → 判"无有效脉动"，参与脱落判决 [实测] */

/*********************************************************************************************************
:*                                              光强自动调节与脱落判决（RoughAdj/FineAdj/JudgeReAdj/ResetAdj）
*********************************************************************************************************/
/* 总开关：1 = 启用移植过来的粗调/细调/重调状态机（它靠"VSIG 的直流电平"判断
 *             光强，要求前端是直流耦合的 PPG 输出）；
 *          0 = 关闭自动调节，DA 固定为起始值，且"粗调完成"恒为真（血氧/脉率
 *              照常计算）。若实测发现 SPO2_VSIG 是交流耦合（无论手指在不在，
 *              直流电平都稳在 1.65V 附近），就把这里置 0，改用固定光强。*/
#define SPO2_ADJ_EN              1u
#define SPO2_IR_CENTRAL_LINE     2000u  /* 红外光调光成功中线（AD 值小于它算"到位"） [实测] */
#define SPO2_RED_CENTRAL_LINE    1700u  /* 红光调光成功中线 [实测] */
/* AD 值小于该值 → 判"光过强/饱和" = 手指脱落。
 * 【本工程实测的取值依据】SPO2_FE_INVERT=0 时，手指拿掉、LED 直射光电管，
 * 实测 IR 归一码值 ≈ 95（见 wave.csv 里 x≥864 那段换算：归一 4000 ? invert=1，
 * 换到 invert=0 就是 raw 95）。MATLAB 原值 80 刚好卡在 95 之下，会漏判，
 * 所以放宽到 150：既留出裕量，又远小于调光中线 2000，不会误判正常工作点。*/
#define SPO2_IR_OFF_MAX_VAL      150u   /* AD 值小于该值 → 判手指脱落 [实测] */
#define SPO2_RED_OFF_MAX_VAL     150u   /* AD 值小于该值 → 判手指脱落 [实测] */

/* ---------- 探头脱落 vs 手指脱落（验收项："自动判别手指脱落与探头脱落"）----------
 * 两种脱落必须在电学上区分开，物理依据是"光电二极管到底有没有收到 LED 的光"：
 *
 *   状态        LED 电流    PD 收光              归一后码值            脉动(PI)
 *   正常        有          有(穿过手指/经反射)   在调光窗内(≈中线)     有
 *   手指脱落    有          直射/漏光, 光很强     逼近 0（下限饱和）    ≈0
 *   探头脱落    **无**(开路) 无, 全黑              逼近 4095（上限饱和） ≈0
 *                                                   ↑ SPO2_PROBE_OFF_CODE_MIN
 * 所以：两个通道的码值**同时**趴在满量程附近 = 一点光都没有 = 探头没接好/断线；
 *       码值趴在 0 附近（光过强）= 探头接了、LED 在发光，只是没夹手指。
 *
 * [实测] 上电后用 CMD_SPO2_STS 看 irAd/redAd 三个状态下的实际值，回填下面两个门限。
 * [注意] 若你的探头是"反射式"（无手指时反而收不到光），则"手指脱落"也会落在
 *        上限侧，此时把 SPO2_PROBE_OFF_EN 置 0：退化为"只判一种脱落"（与改良前一致）。*/
#define SPO2_PROBE_OFF_EN        1u     /* 1=启用探头脱落判别 0=关闭(只报手指脱落)*/
#define SPO2_PROBE_OFF_CODE_MIN  3900u  /* 归一后码值 ≥ 此值 → 判"完全无光" [实测] */
#define SPO2_PROBE_OFF_CNT       5u     /* 连续 N 次判"无光"才确认探头脱落(0.1s/次→0.5s) */
/* 二级判据：光路看起来正常（码值在窗内）但整屏都没有脉动 → 也是手指没夹好。
 * 这一条在"每满一屏"的节拍上生效（一屏 4.096s），所以 N 只能取 1~2，
 * 取大了要等十几秒才报脱落。*/
#define SPO2_FINGER_OFF_CNT      2u     /* 连续 N 屏 PI 不达标才确认(2 屏 ≈ 8s) */
#define SPO2_MAX_CNT_ASTABLE_FINGER   20u  /* 连续 N 次判脱落才确认脱落（防抖） */
#define SPO2_MAX_CNT_STABLE_FINGER    20u  /* 连续 N 次判接入才确认接入（防抖） */
#define SPO2_MAX_CNT_ROUGH_ADJ_IR_COND  3u /* 连续 N 次"到位"才认为红外粗调完成 */
