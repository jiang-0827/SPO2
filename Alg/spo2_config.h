/* MATLAB 是"收满一屏 2048 点才算一次脉率/血氧"的块处理；C 侧保留同样的块窗口：
 * 逐样本写入环形屏缓冲，写满一屏时触发一次 CalcPulseRate + CalcSPO2。*/
#define SPO2_SCREEN_LEN         2048u      /* 4.096 s @500SPS */
#define SPO2_SCREEN_HALF        1024u      /* 幅度谱只画前半段（对应 halfL）*/

/*********************************************************************************************************
:*                                              滤波指标（M5）
*********************************************************************************************************/
#define SPO2_FILT_BIAS_EN       1u     /* 先扣 1.65V 对应码值（整数相减，零相位、零代价） */
#define SPO2_FILT_HP_EN         1u     /* 0.5Hz 二阶高通：去呼吸/体动引起的基线漂移 */
#define SPO2_FILT_FHP           0.5f   /* Hz */
#define SPO2_FILT_NOTCH_EN      0u     /* 50Hz 陷波：MATLAB 侧未做，默认关；现场工频大时打开 */
