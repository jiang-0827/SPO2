/*********************************************************************************************************
* 函数名称：InitSysTick
* 功能功能：初始化SysTick模块
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 生成日期：2018年01月01日
* 注    意：SystemCoreClock/1000  1ms中断一次(计数1000次为1s，每计一次为1ms)
*           SystemCoreClock/1000000 1us中断一次(计数1000000次为1s，每计一次为1us)
*           SysTick_Config()内部使用HCLK作为计数时钟，F407下SystemCoreClock=168MHz
**********************************************************************************************************/
void InitSysTick(void)
{
  InitCycleTimer();                             //先开 DWT：DelayNus 与拍耗时统计都依赖它

  if (SysTick_Config(SystemCoreClock / 1000))   //设置系统滴答定时器1ms中断一次
  {
    while(1)  //配置出错处理，死循环
    {

    }
  }
}

