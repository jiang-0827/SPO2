static  void  ConfigNVIC(void);  //配置NVIC

/*********************************************************************************************************
*                                              内部函数实现
*********************************************************************************************************/
/*********************************************************************************************************
* 函数名称：ConfigNVIC
* 功能功能：配置NVIC
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 生成日期：2018年01月01日
* 注    意：必须在任何调用NVIC_Init()的模块之前执行，否则优先级分组为复位默认值，
*           NVIC_Init()里对抢占/子优先级的划分与预期不符
**********************************************************************************************************/
static  void  ConfigNVIC(void)
{
  NVIC_PriorityGroupConfig(NVIC_PriorityGroup_2); //设置NVIC中断分组2：2位抢占优先级，2位响应优先级
}

/*********************************************************************************************************
*                                              API函数实现
*********************************************************************************************************/
/*********************************************************************************************************
* 函数名称：InitNVIC
* 功能功能：初始化NVIC模块
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 生成日期：2018年01月01日
* 注    意：
**********************************************************************************************************/
void InitNVIC(void)
{
  ConfigNVIC();  //配置NVIC
}
