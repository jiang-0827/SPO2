/*********************************************************************************************************
* 模块名称：SPO2_Algorithm.h
* 摘    要：血氧饱和度 (SpO2) 与脉率 (PR) 算法处理头文件
*           包含 DC 基线跟踪、AC 平滑滤波、动态寻峰寻谷、R值中值滤波查表及脱落检测
* 当前版本：1.0.0
*********************************************************************************************************/
#ifndef _SPO2_ALGORITHM_H_
#define _SPO2_ALGORITHM_H_

#include "DataType.h"

/*********************************************************************************************************
*                                              宏定义
*********************************************************************************************************/
#define SPO2_SAMPLE_RATE_HZ     200     /* 采样频率 200Hz (每 5ms 一次) */

/*********************************************************************************************************
*                                              枚举结构体定义
*********************************************************************************************************/
typedef enum {
  SPO2_STATUS_NORMAL = 0,       /* 信号正常，计算有效 */
  SPO2_STATUS_FINGER_OFF = 1,   /* 手指脱落 */
  SPO2_STATUS_PROBE_OFF = 2,    /* 探头脱落 */
  SPO2_STATUS_CALCULATING = 3   /* 正在收敛计算中 */
} SPO2_Status_t;

typedef struct {
  float fDCRed;
  float fDCIr;
  float fACRed;
  float fACIr;

  float fDispRed;
  float fDispIr;

  u8            u8SpO2;
  u16           u16PulseRate;
  float         fRVal;
  SPO2_Status_t status;
} SPO2_Result_t;

/*********************************************************************************************************
*                                              API 函数声明
*********************************************************************************************************/
void SPO2_AlgInit(void);
void SPO2_AlgProcess(u16 rawRed, u16 rawIr, u16 rawDark);
void SPO2_GetResult(SPO2_Result_t* pResult);

#endif
