#ifndef _PROC_HOST_CMD_H_
#define _PROC_HOST_CMD_H_

/*********************************************************************************************************
:*                                              包含头文件
*********************************************************************************************************/
#include "DataType.h"

/*********************************************************************************************************
:*                                              宏定义
*********************************************************************************************************/
//---------- MODULE_SPO2(0x33) 模块在本工程新增的二级ID（0x02/0x03/0x80 见 PackUnpack.h）----------
#define  CMD_SPO2_SET_INT    0x81   //手动设置光强，arrData[0..1]=红外DA(小端), arrData[2..3]=红光DA(小端)
#define  CMD_SPO2_GET_RSLT   0x82   //查询血氧结果，回一帧 DAT_SPO2_RESULT + 打印一行
#define  CMD_SPO2_RST        0x83   //算法复位（等价于 MATLAB 的 InitData + ResetAdj）
#define  CMD_SPO2_STS        0x84   //查询运行状态（打印一行）
#define  CMD_SPO2_SET_SETTLE 0x85   //设置前端通道建立延时，arrData[0..1]=μs(小端)
#define  CMD_SPO2_SET_INV    0x86   //设置极性归一，arrData[0]=0/1
#define  CMD_SPO2_SET_CH     0x87   //切换ADC规则通道，arrData[0]=ADC_Channel_x
#define  CMD_SPO2_CLR_CNT    0x88   //清零统计量
//---------- 以下三条为"五参数验收"新增 ----------
#define  CMD_SPO2_R_CAL      0x89   //R值现场标定：arrData[0..1]=增益千分比(小端,500~1500)
                                    //                arrData[2..3]=偏置(i16小端,-300~300)
                                    //                返回后打印标定结果；标定参数跨复位保留
#define  CMD_SPO2_DUMP_AD    0x8A   //导出 1024 点原始 AD（验收要求"≥1000 点真实数据"）
                                    //  以文本行从最新点倒序输出，约 1.28s 发完，非阻塞
#define  CMD_SPO2_GET_METRIC 0x8B   //查询血氧指标：回一帧 DAT_SPO2_METRIC + 打印一行
                                    //  （PI、脱落状态、R 值）

//---------- MODULE_SYS(0x01) 模块的上位机原生命令 ----------
#define  CMD_MODULE_TYPE     0x91   //模块类型设置（上位机 gCmdModuleType 用的就是 0x91）

/*********************************************************************************************************
:*                                              枚举结构体定义
*********************************************************************************************************/
//应答消息定义
typedef enum{
  CMD_ACK_OK,           //0 命令成功
  CMD_ACK_CHECKSUM,     //1 校验和错误
  CMD_ACK_LEN,          //2 命令包长度错误
  CMD_ACK_BAD_CMD,      //3 无效命令
  CMD_ACK_PARAM_ERR,    //4 命令参数数据错误
  CMD_ACK_NOT_ACC       //5 命令不接受
}EnumCmdAckType;

/*********************************************************************************************************
:*                                              API函数声明
*********************************************************************************************************/
void  InitProcHostCmd(void);    //初始化ProcHostCmd模块
void  ProcHostCmd(u8 recData);  //处理主机命令

#endif
