/*********************************************************************************************************
:*                                              API函数声明
*********************************************************************************************************/
void  SetWaveSendEnable(u8 en);       //设置波形数据帧上传开关，1-上传，0-停止
u8    GetWaveSendEnable(void);        //获取波形数据帧上传开关

const spo2_result_t* GetSPO2Result(void);       //读取血氧算法最新结果（供命令处理/上报用）
void  SPO2AlgReset(void);                       //血氧算法整机复位（清屏 + 重新标定）
void  SPO2SetManualLight(u16 irDa, u16 redDa);  //上位机接管光强（对应调光命令）

/* 原始 AD 数据导出（对应验收前置条件"至少采样1000个真实AD数据"）：
 * 启动后由 2ms 任务分片非阻塞地打出 1024 对原始码值（文本行，从最新点倒序），
 * 约 1.28s 发完；期间自动停发波形/光强帧，避免污染文本流。*/
void  SPO2DumpAdStart(void);                    //启动导出
u8    SPO2DumpAdIsBusy(void);                   //1=正在导出
u8    SPO2DumpAdGetDropCnt(void);               //本次导出被串口队列丢掉的字节数(0 为理想)

/* R 值现场标定（验收"血氧误差 ±2%"的调节手段）：gainPm 千分比增益 500~1500，
 * offset 绝对偏置 -300~300；返回 1-成功 0-参数越界。标定参数跨复位保留。*/
u8    SPO2SetRCal(i16 gainPm, i16 offset);
void  SPO2GetRCal(i16* pGainPm, i16* pOffset);

/* ---- 实时性可观测性(2026-10-09 新增，与 Timer 的 miss 计数配套) ----
 * 这些量回答的是"采样链路有没有在偷偷丢数据、余量还剩多少"：
 *   tickMax  = 一拍(采集+算法+上报)的最长耗时，预算 2000us；
 *   heavyMax = 一次屏级重算(屏统计+R+PI)的最长耗时；
 *   heavyRun = 屏级重算执行次数(应与屏数一致，每 4.096s 一次)；
 *   lostScreen = 被覆写丢掉的屏数，应为 0。
 * 采集侧的 conv/timeout/ovr 发现不了"整拍被拖长"，所以必须在这里补。
 * 统计在拍内只多两次 DWT 读数与一次比较，不影响采样时序。*/
u32   SPO2GetTickMaxUs(void);       //单拍最长耗时 us
u32   SPO2GetHeavyMaxUs(void);      //屏级重算最长耗时 us(屏统计+R+PI)
u32   SPO2GetHeavyRunCnt(void);     //屏级重算执行次数
u32   SPO2GetScreenLostCnt(void);   //被覆写丢弃的屏数(应为 0)
void  SPO2ClrTickStat(void);        //清零上述统计量(命令 0x88 调用)
