void  InitSendDataToHost(void);         //初始化SendDataToHost模块
void  SendAckPack(u8 moduleId, u8 secondId, u8 ackMsg); //发送命令应答数据包

void  SendSPO2ResultToHost(i16 spo2, i16 pulseRate, u16 fundHzX100); //发送血氧结果帧(二级ID 0x04)
/* 发送血氧指标帧(二级ID 0x05，本工程新增)：
 *   验收项"灌注指数 3%"/"自动判别手指脱落与探头脱落"/"血氧 ±2%(看 R 值)"都靠这一帧。*/
void  SendSPO2MetricToHost(u16 piIrX100, u8 offState, u8 flags, u16 rValInt);

/* ---- 文本类上行输出(取代 printf)，与波形/协议帧共用同一发送队列 ----
 * 为什么必须这样：printf 走 fputc 是"直写 DR + 死等 TC"的阻塞写法，115200 下
 * 每字节约 87us；一次 10 行状态打印(~600 字节)会把 2ms 任务堵住约 50ms(丢约 25 对
 * 采样)，还会与 TXE 中断并发争抢串口，破坏正在发送的协议帧/CSV 的字节间隔。
 * 心电工程早已改走队列(见其 Main.c 状态行注释)，本工程在此补齐同一写法。
 * 上电自检 PrintBootInfo 仍用 printf：那时队列与中断都还没开始跑，无并发风险。*/
#define  SPO2_LOG_MAX_LEN   192      //单条日志上限(超长截断，'\0' 结尾由 vsnprintf 保证)

void  SendTextToHost(const char *pText);   //把一段文本压入发送队列(非阻塞)
void  LogPrintf(const char *pFmt, ...);    //格式化日志 → 发送队列(取代 printf)
#endif
