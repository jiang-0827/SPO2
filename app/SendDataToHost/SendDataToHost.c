/*********************************************************************************************************
* 函数名称：SendPackToHost
* 函数功能：打包数据，并将数据发送到主机
* 输入参数：pPackSent，指向结构体变量的地址
* 输出参数：void
* 返 回 值：void
* 创建日期：2018年01月01日
* 注    意：
*********************************************************************************************************/
static  void  SendPackToHost(StructPackType* pPackSent)
{
  u8  packValid = 0;  //打包正确标志位，默认值为0

  packValid = PackData(pPackSent);  //打包数据
  
  if(0 < packValid)                 //如果打包正确
  {
    WriteUART1((u8*)pPackSent, 10); //写数据到串口
  }
}

