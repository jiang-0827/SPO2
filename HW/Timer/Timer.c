/*********************************************************************************************************
* 函数名称：InitTimer
* 功能功能：初始化Timer模块
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 生成日期：2026年09月20日
* 注    意：需先调用InitRCC()，本函数依赖其查询到的定时器时钟
**********************************************************************************************************/
void InitTimer(void)
{
  ConfigTimer4();   //配置TIM4，1ms中断一次，用于产生2ms时间片标志
  ConfigTimer5();   //配置TIM5，1ms中断一次，用于产生1s时间片标志
}

