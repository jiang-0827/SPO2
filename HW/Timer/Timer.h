void  InitTimer(void);      //初始化Timer模块

u8    Get2msFlag(void);     //获取2ms标志
void  Clr2msFlag(void);     //清除2ms标志

u8    Get1SecFlag(void);    //获取1s标志
void  Clr1SecFlag(void);    //清除1s标志

/* ---- 2ms 拍的丢拍统计(2026-10-09 新增) ----
 * 时基是"单位标志位 + 主循环轮询"：主循环一旦慢过 2ms，这一拍的 IR/RED 成对采样
 * 就丢了，而且原本毫无痕迹(ADC 的 conv/timeout/ovr 三项统计都发现不了它)。
 * 现在 ISR 里如实记账，miss 应恒为 0 —— 这是验收 T6"无超时、无溢出、无丢帧"
 * 真正的量化判据。*/
u32   Get2msTickCnt(void);    //累计到期的 2ms 拍数(硬件时基，含被丢弃的拍)
u32   Get2msMissCnt(void);    //累计丢拍数(上一拍未被消费就又到期 = 少采一对 IR/RED)
void  ClearTickStatic(void);  //清零上述统计量(挂到命令 0x88"清零统计量")
#endif
