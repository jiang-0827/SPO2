/*********************************************************************************************************
:* 模 块 名 称：ADC.h
:* 摘        要：ADC模块，血氧前端 SPO2_VSIG 的单通道软件触发采集 + 统计量
:* 当前版本：1.0.0
:* 作        者：Jaziel.Jiang(COPYRIGHT 2018 - 2026 Jaziel.Jiang. All rights reserved.)
:* 生成日期：2026年09月24日
:* 说        明：本文件由心电工程(HW/ADC/ADC.c)移植而来，"定时器触发→ADC→DMA→环形队列"
:*               那条链路**被刻意去掉**了，原因见下面的"与心电工程的差异"
:* 注        意：
:**********************************************************************************************************
:* 与心电工程(HW/ADC)的差异，以及为什么：
:*   1) 心电前端是"一路模拟信号、连续等间隔采样"，所以可以用 TIM2 TRGO 硬件触发 +
:*      DMA 循环搬运 + 环形队列，采样节拍由硬件保证，CPU 零参与。
:*   2) 血氧前端是"单路 SPO2_VSIG + 两个选通脚(IR_CS/RED_CS)分时复用"，一个采样
:*      节拍里必须先切通道、等前端建立、再转换，两次转换之间夹着 GPIO 翻转 ——
:*      硬件触发链路无法表达这种"依赖软件状态"的时序，所以改由 2ms 时间片里的
:*      软件时序驱动（见 HW/SPO2FE/SPO2FE.c 的 SPO2FE_ReadPair）。
:*   3) 因此本模块只剩"配置 + 单次软件触发转换 + 统计"，不再有队列/U16Queue.c。
:**********************************************************************************************************
:* 硬件连接（依据 SCH_Schematic1_2026-09-22 血氧板的 H4"单片机引脚"7pin 排针）：
:*   H4-4  SPO2_VSIG  →  PA5 (ADC12_IN5)  模拟输入，前端脉搏波输出
:*   H4-7  SPO2_DAI   →  PA4 (DAC_OUT1)   光强控制（在 HW/SPO2FE 里初始化）
:*   H4-6  SPO2_IR_CS →  GPIO 数字输出    红外通道选通（在 HW/SPO2FE 里初始化）
:*   H4-3  SPO2_RED_CS→  GPIO 数字输出    红光通道选通（在 HW/SPO2FE 里初始化）
:*   H4-2  +5V        →  5V（血氧板自己用 RT9193 转 3V3A，MCU 侧不给 3V3）
:*   H4-1  GND        →  GND
:*   H4-5  NC
:* 注意 PA4/PA5 同时是 DAC_OUT1/DAC_OUT2：本工程把 PA4 给 DAC(光强)、PA5 给 ADC(信号)，
:* 两者互不冲突；若要改用其它引脚，请同步修改 ADC.h / SPO2FE.h 里的宏。
:*********************************************************************************************************/
#ifndef _ADC_H_
#define _ADC_H_

/*********************************************************************************************************
:*                                              包含头文件
*********************************************************************************************************/
#include "DataType.h"

/*********************************************************************************************************
:*                                              宏定义
*********************************************************************************************************/
#define ADC_VSIG_CHANNEL    ADC_Channel_5   //SPO2_VSIG 所在规则通道(PA5 = ADC12_IN5)
#define ADC_VREF_MV         3300            //ADC满量程参考电压(mV)：VDDA=3.3V
                                            //  血氧板的 VREF 由板上 3V3A 分压得到(=1.65V)，
                                            //  若实测 VDDA 与板上 3V3A 有明显偏差，会引入
                                            //  光强中线的系统误差，用这个宏做标定补偿
#define ADC_SAMPLE_TIME     ADC_SampleTime_480Cycles  //前端输出阻抗低，取长采样时间换取抗扰度

/*********************************************************************************************************
:*                                              枚举结构体定义
*********************************************************************************************************/

/*********************************************************************************************************
:*                                              API函数声明
*********************************************************************************************************/
void  InitADC(void);                     //初始化ADC模块(ADC1 + SPO2_VSIG 引脚)

u16   ADCConvertChannel(u8 channel);     //对指定规则通道做一次软件触发转换(阻塞等待EOC，带超时)
u16   ADCConvertVsig(void);              //对当前 SPO2_VSIG 通道做一次转换
u16   ADCConvertVsigAvg(u8 n);           //对当前 SPO2_VSIG 通道连转 n 次取平均(过采样降噪)
void  SetADCChannel(u8 channel);         //切换ADC规则通道(取值为 ADC_Channel_x)
u8    GetADCChannel(void);               //获取当前ADC规则通道

u16   GetADCVoltageMv(u16 raw);          //把ADC原始码换算成毫伏

u32   GetADCConvCnt(void);               //获取累计转换次数
u32   GetADCTimeoutCnt(void);            //获取转换超时次数(诊断，正常为0)
u32   GetADCOvrCnt(void);                //获取ADC溢出(OVR)次数(诊断，正常为0)
void  ClearADCStatic(void);              //清零统计量

#endif
