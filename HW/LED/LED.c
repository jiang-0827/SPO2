#include "LED.h"
#include "stm32f4xx_conf.h"

/*********************************************************************************************************
*                                              宏定义
*********************************************************************************************************/
#define  LED_GPIO_PORT   GPIOB      //LED所在端口
#define  LED_GPIO_PIN    GPIO_Pin_2  //LED所在引脚(PB2)
#define  LED_GPIO_RCC    RCC_AHB1Periph_GPIOB  //LED端口时钟(F4的GPIO在AHB1，F1在APB2)

/*********************************************************************************************************
*                                              枚举结构体定义
*********************************************************************************************************/

/*********************************************************************************************************
*                                              内部变量
*********************************************************************************************************/

/*********************************************************************************************************
*                                              内部函数声明
*********************************************************************************************************/
static  void  ConfigLEDGPIO(void);  //配置LED的GPIO

/*********************************************************************************************************
*                                              内部函数实现
*********************************************************************************************************/
/*********************************************************************************************************
* 函数名称：ConfigLEDGPIO
* 功能功能：配置LED的GPIO
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 生成日期：2026年09月20日
* 注    意：F4的GPIO初始化比F1多了OType/PuPd/Speed三个参数
**********************************************************************************************************/
static  void  ConfigLEDGPIO(void)
{
  GPIO_InitTypeDef GPIO_InitStructure;  //GPIO_InitStructure用于存GPIO的参数

  //使用RCC模块时钟
  RCC_AHB1PeriphClockCmd(LED_GPIO_RCC, ENABLE); //使能LED所在GPIO时钟

  GPIO_InitStructure.GPIO_Pin   = LED_GPIO_PIN;             //引脚定义
  GPIO_InitStructure.GPIO_Mode  = GPIO_Mode_OUT;            //输出模式
  GPIO_InitStructure.GPIO_OType = GPIO_OType_PP;            //推挽输出
  GPIO_InitStructure.GPIO_PuPd  = GPIO_PuPd_NOPULL;         //不上拉不下拉
  GPIO_InitStructure.GPIO_Speed = GPIO_Speed_2MHz;          //LED开关速度慢即可，降低噪声
  GPIO_Init(LED_GPIO_PORT, &GPIO_InitStructure);            //根据参数初始化LED的GPIO

  GPIO_SetBits(LED_GPIO_PORT, LED_GPIO_PIN);                //上电默认熄灭LED(低电平点亮)
}

/*********************************************************************************************************
*                                              API函数实现
*********************************************************************************************************/
/*********************************************************************************************************
* 函数名称：InitLED
* 功能功能：初始化LED模块
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 生成日期：2026年09月20日
* 注    意：
**********************************************************************************************************/
void InitLED(void)
{
  ConfigLEDGPIO();  //配置LED的GPIO
}

/*********************************************************************************************************
* 函数名称：LEDSet
* 功能功能：点亮或熄灭LED
* 输入参数：on，1-点亮，0-熄灭
* 输出参数：void
* 返 回 值：void
* 生成日期：2026年09月20日
* 注    意：低电平点亮，故写入的电平与on相反
**********************************************************************************************************/
void  LEDSet(u8 on)
{
  if(on != LED_OFF)
  {
    GPIO_ResetBits(LED_GPIO_PORT, LED_GPIO_PIN);  //拉低点亮
  }
  else
  {
    GPIO_SetBits(LED_GPIO_PORT, LED_GPIO_PIN);    //拉高熄灭
  }
}

/*********************************************************************************************************
* 函数名称：LEDGet
* 功能功能：读取LED当前状态
* 输入参数：void
* 输出参数：void
* 返 回 值：1-点亮，0-熄灭
* 生成日期：2026年09月20日
* 注    意：
**********************************************************************************************************/
u8  LEDGet(void)
{
  return(GPIO_ReadOutputDataBit(LED_GPIO_PORT, LED_GPIO_PIN) == Bit_RESET) ? 1 : 0;
}

/*********************************************************************************************************
* 函数名称：LEDFlicker
* 功能功能：LED闪烁函数
* 输入参数：cnt
* 输出参数：void
* 返 回 值：void
* 生成日期：2026年09月20日
* 注    意：LEDFlicker在Proc2msTask中调用，cnt为250时表示每500ms翻转一次LED状态
**********************************************************************************************************/
void LEDFlicker(u16 cnt)
{
  static u16 s_iCnt;  //定义静态变量s_iCnt作为计数器

  s_iCnt++; //计数器的计数值加1

  if(s_iCnt >= cnt)   //计数器的计数值大于cnt
  {
    s_iCnt = 0;       //设置计数器的计数值为0

    //LED状态取反实现LED闪烁
    GPIO_WriteBit(LED_GPIO_PORT, LED_GPIO_PIN,
                  (BitAction)(1 - GPIO_ReadOutputDataBit(LED_GPIO_PORT, LED_GPIO_PIN)));
  }
}
