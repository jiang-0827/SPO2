/*********************************************************************************************************
*                                              内部变量
*********************************************************************************************************/
static  RCC_ClocksTypeDef  s_structClocks;  //各级总线时钟频率缓存
static  u32  s_iAPB1TimClk = 84000000;      //APB1定时器时钟(HZ)，默认按84MHz
static  u32  s_iAPB2TimClk = 84000000;      //APB2定时器时钟(HZ)，默认按84MHz
static  u8   s_iPllRdy     = 0;             //PLL锁定标志，1-已锁定

/*********************************************************************************************************
*                                              内部函数声明
*********************************************************************************************************/
static  void  ConfigRCC(void);  //配置(查询)RCC

/*********************************************************************************************************
*                                              内部函数实现
*********************************************************************************************************/
/*********************************************************************************************************
* 函数名称：ConfigRCC
* 功能功能：查询并缓存各级时钟频率
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 生成日期：2026年09月20日
* 注    意：系统时钟168MHz已由启动文件中的SystemInit()配置完成，本函数不再改写时钟；
*           定时器时钟换算规则(与F103一致)：APB总线分频系数为1时，定时器时钟=PCLK×1；
*           分频系数不为1时，定时器时钟=PCLK×2
*           天空星F407默认(168MHz)：PCLK1=42MHz(APB1/4)→TIM2~5、TIM12~14=84MHz；
*                                    PCLK2=84MHz(APB2/2)→TIM1、TIM8=168MHz
**********************************************************************************************************/
static  void  ConfigRCC(void)
{
  s_iPllRdy = (RCC_GetFlagStatus(RCC_FLAG_PLLRDY) != RESET) ? 1 : 0;

  RCC_GetClocksFreq(&s_structClocks);  //读取当前各总线实际频率

  //APB1定时器时钟：PCLK1等于HCLK说明分频为1(×1)，否则分频不为1(×2)
  if(s_structClocks.PCLK1_Frequency == s_structClocks.HCLK_Frequency)
  {
    s_iAPB1TimClk = s_structClocks.PCLK1_Frequency;
  }
  else
  {
    s_iAPB1TimClk = s_structClocks.PCLK1_Frequency * 2;
  }

  //APB2定时器时钟：规则同上
  if(s_structClocks.PCLK2_Frequency == s_structClocks.HCLK_Frequency)
  {
    s_iAPB2TimClk = s_structClocks.PCLK2_Frequency;
  }
  else
  {
    s_iAPB2TimClk = s_structClocks.PCLK2_Frequency * 2;
  }
}

/*********************************************************************************************************
*                                              API函数实现
*********************************************************************************************************/
/*********************************************************************************************************
* 函数名称：InitRCC
* 功能功能：初始化RCC模块
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 生成日期：2026年09月20日
* 注    意：必须最先调用，其它模块(Timer/ADC)要用这里的频率算分频
**********************************************************************************************************/
void InitRCC(void)
{
  ConfigRCC();  //查询并缓存各级时钟频率
}

/*********************************************************************************************************
* 函数名称：GetSysClockFreq
* 功能功能：获取系统时钟频率
* 输入参数：void
* 输出参数：void
* 返 回 值：SYSCLK频率(HZ)
* 生成日期：2026年09月20日
* 注    意：
**********************************************************************************************************/
u32  GetSysClockFreq(void)
{
  return(s_structClocks.SYSCLK_Frequency);
}

/*********************************************************************************************************
* 函数名称：GetAPB1TimClockFreq
* 功能功能：获取APB1上定时器时钟频率
* 输入参数：void
* 输出参数：void
* 返 回 值：时钟频率(HZ)
* 生成日期：2026年09月20日
* 注    意：TIM2/TIM3/TIM4/TIM5/TIM6/TIM7/TIM12/TIM13/TIM14用该频率
**********************************************************************************************************/
u32  GetAPB1TimClockFreq(void)
{
  return(s_iAPB1TimClk);
}

/*********************************************************************************************************
* 函数名称：GetAPB2TimClockFreq
* 功能功能：获取APB2上定时器时钟频率
* 输入参数：void
* 输出参数：void
* 返 回 值：时钟频率(HZ)
* 生成日期：2026年09月20日
* 注    意：TIM1/TIM8/TIM9/TIM10/TIM11用该频率
**********************************************************************************************************/
u32  GetAPB2TimClockFreq(void)
{
  return(s_iAPB2TimClk);
}

/*********************************************************************************************************
* 函数名称：GetAPB2ClockFreq
* 功能功能：获取APB2总线(PCLK2)频率，ADC的时钟源
* 输入参数：void
* 输出参数：void
* 返 回 值：时钟频率(HZ)
* 生成日期：2026年09月20日
* 注    意：ADCCLK = PCLK2 / ADC预分频，F407的ADCCLK最大允许42MHz
**********************************************************************************************************/
u32  GetAPB2ClockFreq(void)
{
  return(s_structClocks.PCLK2_Frequency);
}

/*********************************************************************************************************
* 函数名称：IsRunByPLL
* 功能功能：判断系统时钟源是否为PLL
* 输入参数：void
* 输出参数：void
* 返 回 值：1-PLL，0-非PLL(HSI/HSE)
* 生成日期：2026年09月20日
* 注    意：返回0通常意味着8MHz晶振没起振，此时SystemCoreClock仍是168MHz但实际主频
*           只有16MHz(HSI)，所有靠主频算出来的定时/波特率都会偏4倍，上电自检必须查
**********************************************************************************************************/
u8  IsRunByPLL(void)
{
  return(s_iPllRdy);
}
